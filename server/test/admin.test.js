const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const Database = require('better-sqlite3');
const { createAdminApp } = require('../src/admin');
const security = require('../src/security');

test('管理画面は認証とアクセス元を検証し、受付と人数を記録する', async (t) => {
  process.env.DATA_ENCRYPTION_KEY_B64 = crypto.randomBytes(32).toString('base64');
  process.env.IDENTIFIER_HMAC_SECRET = crypto.randomBytes(32).toString('hex');
  process.env.ADMIN_PASSWORD_HASH = await security.hashPassphrase('secure-password-123');
  const db = new Database(':memory:');
  db.pragma('foreign_keys = ON');
  db.exec(fs.readFileSync(path.join(__dirname, '../src/schema.sql'), 'utf8'));
  db.prepare('INSERT INTO slots(id,title,start_at,end_at,capacity) VALUES(?,?,?,?,?)').run('slot', '発表', '2099-01-01T10:00:00+09:00', '2099-01-01T11:00:00+09:00', 10);
  db.prepare(`INSERT INTO reservations(id,slot_id,email_ciphertext,email_hash,passphrase_hash,device_hash,party_size,status,email_status) VALUES(?,?,?,?,?,?,?,'confirmed','sent')`).run('id-1', 'slot', security.encryptText('visitor@example.com'), 'hash', 'hash', 'device', 3);
  let broadcasts = 0;
  const server = createAdminApp({ db, broadcast: () => { broadcasts++; } }).listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); db.close(); });
  const host = `127.0.0.1:${server.address().port}`, base = `http://${host}`;
  const post = (url, body, cookie, origin = `https://${host}`) => fetch(base + url, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin, ...(cookie ? { Cookie: cookie } : {}) }, body: JSON.stringify(body) });
  assert.equal((await fetch(base + '/admin-api/dashboard')).status, 401);
  assert.equal((await post('/admin-api/delete', { id: 'id-1' })).status, 401);
  assert.equal((await post('/admin-api/login', { password: 'bad' })).status, 401);
  assert.equal((await post('/admin-api/login', { password: 'secure-password-123' }, null, 'https://evil.example')).status, 403);
  const login = await post('/admin-api/login', { password: 'secure-password-123' });
  assert.equal(login.status, 200);
  assert.match(login.headers.get('set-cookie'), /HttpOnly; Secure; SameSite=Strict/);
  const cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await post('/admin-api/checkin', { id: 'id-1', checkedIn: true }, cookie, 'https://evil.example')).status, 403);
  assert.equal((await post('/admin-api/checkin', { id: 'id-1', checkedIn: true }, cookie)).status, 200);
  let dashboard = await (await fetch(base + '/admin-api/dashboard', { headers: { Cookie: cookie } })).json();
  assert.equal(dashboard.slots[0].checked_in, 3);
  assert.equal(dashboard.reservations[0].email, 'visitor@example.com');
  assert.match(dashboard.familyCode, /^[A-Z2-9]{12}$/);
  assert.equal(dashboard.reservations[0].booking_type, 'general');
  assert.equal((await post('/admin-api/checkin', { id: 'id-1', checkedIn: false }, cookie)).status, 200);
  dashboard = await (await fetch(base + '/admin-api/dashboard', { headers: { Cookie: cookie } })).json();
  assert.equal(dashboard.slots[0].checked_in, 0);
  assert.equal((await post('/admin-api/checkin', { id: 'id-1', checkedIn: true }, cookie)).status, 200);
  assert.equal((await post('/admin-api/delete', { id: 'id-1' }, cookie, 'https://evil.example')).status, 403);
  assert.equal((await post('/admin-api/delete', { id: '' }, cookie)).status, 400);
  assert.equal((await post('/admin-api/delete', { id: 'id-1' }, cookie)).status, 200);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM reservations').get().n, 0);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM checkins').get().n, 0);
  assert.equal(broadcasts, 1);
  dashboard = await (await fetch(base + '/admin-api/dashboard', { headers: { Cookie: cookie } })).json();
  assert.equal(dashboard.slots[0].reserved, 0);
  assert.equal(dashboard.slots[0].checked_in, 0);
  assert.equal((await post('/admin-api/delete', { id: 'id-1' }, cookie)).status, 404);
  await post('/admin-api/logout', {}, cookie);
  assert.equal((await fetch(base + '/admin-api/dashboard', { headers: { Cookie: cookie } })).status, 401);
});

